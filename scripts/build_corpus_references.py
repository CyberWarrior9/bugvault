#!/usr/bin/env python3
"""Generate per-skill corpus reference files from an h1-corpus SQLite build.

One `references/corpus.md` per hunt skill, containing:

  * how many disclosed reports exist for that class, how many carry a full body,
    and the bounty distribution
  * the highest-bounty disclosed reports, by id and URL
  * the exact `reports_fts` query to re-run, so the skill points at the corpus
    rather than duplicating it

Deliberately NOT included: payload text. The corpus holds 1,593 payloads, and
inlining them into a skill reference would hand the model a payload library, which
cuts against the engine's design (modules hold no payload literals; payloads come
from the generator and are recorded with authorship through `fields.record_payload`).
The payload *count* per class is given, with the query to read them, so the material
is reachable without being pre-loaded.

SKILL.md files are never written to. Only `references/corpus.md` is created.

Report titles and programs are upstream data from public disclosures. They are
quoted as facts about what was reported, not as instructions.

Usage:
    python3 scripts/build_corpus_references.py [--corpus PATH] [--check]
"""
from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

REPO = Path(__file__).resolve().parent.parent
DEFAULT_CORPUS = REPO / "vault/_data/corpora/h1-corpus.sqlite3"
SKILLS = REPO / ".claude/skills"
TOP_N = 12

# skill id -> the corpus attack classes that bear on it. A skill may draw on more
# than one; `hunt-security-misconfig` is the clearest case.
SKILL_CLASSES: Dict[str, Sequence[str]] = {
    "hunt-xss": ("Cross-Site Scripting",),
    "hunt-csrf": ("Cross-Site Request Forgery",),
    "hunt-ssrf": ("Server-Side Request Forgery",),
    "hunt-sqli": ("SQL & Data-Layer Injection",),
    "hunt-idor": ("Access Control & IDOR",),
    "hunt-access-control": ("Access Control & IDOR",),
    "hunt-ato": ("Authentication, Sessions & MFA",),
    "hunt-auth-bypass": ("Authentication, Sessions & MFA",),
    "hunt-mfa-bypass": ("Authentication, Sessions & MFA",),
    "hunt-oauth": ("OAuth, SSO & Federation",),
    "hunt-saml": ("OAuth, SSO & Federation",),
    "hunt-xxe": ("XML & XXE",),
    "hunt-ssti": ("Command, Code & Template Injection",),
    "hunt-rce": ("Command, Code & Template Injection", "Deserialization & Object Injection"),
    "hunt-file-upload": ("File, Path & Upload",),
    "hunt-business-logic": ("Business Logic & Abuse",),
    "hunt-race-conditions": ("Race Conditions & Concurrency",),
    "hunt-http-smuggling": ("HTTP Desync & Request Smuggling",),
    "hunt-cache": ("Cache Poisoning & Web Cache",),
    "hunt-takeover": ("DNS & Subdomain Takeover",),
    "hunt-graphql": ("API, GraphQL & WebSocket",),
    "hunt-js-bundle": ("Information Disclosure & Privacy",),
    "hunt-cloud-misconfig": ("Configuration & Hardening",),
    "hunt-security-misconfig": ("Configuration & Hardening", "Clickjacking & UI Redress",
                                "CORS & Cross-Origin Policy", "Cryptography & Transport Security"),
}

# Corpus payload class_name values, mapped to the skill that would use them.
PAYLOAD_CLASSES: Dict[str, str] = {
    "hunt-xss": "xss", "hunt-sqli": "sqli", "hunt-ssrf": "ssrf", "hunt-ssti": "ssti",
    "hunt-rce": "rce", "hunt-xxe": "xxe", "hunt-idor": "idor",
    "hunt-file-upload": "path-traversal",
}


def fetch(con: sqlite3.Connection, classes: Sequence[str]) -> Tuple[dict, List[sqlite3.Row]]:
    marks = ",".join("?" for _ in classes)
    stat = con.execute(
        f"SELECT COUNT(*) n, SUM(body_available) bodies, SUM(bounty>0) paid, "
        f"CAST(COALESCE(MAX(bounty),0) AS INT) mx, CAST(COALESCE(AVG(NULLIF(bounty,0)),0) AS INT) avg, "
        f"MIN(year) y0, MAX(year) y1 "
        f"FROM reports WHERE primary_class IN ({marks})", tuple(classes)).fetchone()
    top = con.execute(
        f"SELECT id, title, url, program, CAST(COALESCE(bounty,0) AS INT) b, year, severity "
        f"FROM reports WHERE primary_class IN ({marks}) "
        f"ORDER BY COALESCE(bounty,0) DESC, COALESCE(votes,0) DESC LIMIT ?",
        tuple(classes) + (TOP_N,)).fetchall()
    return dict(stat), list(top)


def render(skill: str, classes: Sequence[str], stat: dict, top: List[sqlite3.Row],
           payload_class: str | None, payload_n: int, corpus_rel: str) -> str:
    L: List[str] = []
    L.append(f"# Disclosed-report corpus — `{skill}`")
    L.append("")
    L.append(f"Generated by `scripts/build_corpus_references.py` from `{corpus_rel}`.")
    L.append("Precedent, not evidence: a disclosed report shows a bug was accepted "
             "somewhere, never that this target has it.")
    L.append("")
    L.append("## Corpus classes read for this skill")
    L.append("")
    for c in classes:
        L.append(f"- `{c}`")
    L.append("")
    n = stat.get("n") or 0
    L.append("## Scale")
    L.append("")
    L.append("| | |")
    L.append("|---|---|")
    L.append(f"| Reports | **{n}** |")
    L.append(f"| With a full body | {stat.get('bodies') or 0} |")
    L.append(f"| Bountied | {stat.get('paid') or 0} |")
    if stat.get("mx"):
        L.append(f"| Max bounty | ${stat['mx']:,} |")
        L.append(f"| Mean of bountied | ${stat.get('avg') or 0:,} |")
    if stat.get("y0"):
        L.append(f"| Years | {stat['y0']}–{stat['y1']} |")
    if payload_class:
        L.append(f"| Payloads recorded | {payload_n} (class `{payload_class}`) |")
    L.append("")
    if top:
        L.append("## Highest-bounty disclosures")
        L.append("")
        L.append("| Bounty | Report | Title |")
        L.append("|---|---|---|")
        for r in top:
            title = (r["title"] or "").replace("|", "\\|")[:88]
            bounty = f"${r['b']:,}" if r["b"] else "—"
            L.append(f"| {bounty} | [{r['id']}]({r['url']}) | {title} |")
        L.append("")
    L.append("## Queries")
    L.append("")
    L.append("Full-text over report bodies (68.1 MB across 9,742 reports):")
    L.append("")
    L.append("```sh")
    L.append(f"sqlite3 {corpus_rel} \\")
    L.append("  \"SELECT report_id, substr(title,1,70) FROM reports_fts \\")
    L.append("   WHERE reports_fts MATCH 'YOUR TERMS' LIMIT 20;\"")
    L.append("```")
    L.append("")
    L.append("Every report for this skill's classes:")
    L.append("")
    quoted = ", ".join(f"'{c}'" for c in classes)
    L.append("```sh")
    L.append(f"sqlite3 {corpus_rel} \\")
    L.append(f"  \"SELECT id, bounty, title FROM reports \\")
    L.append(f"   WHERE primary_class IN ({quoted}) ORDER BY bounty DESC;\"")
    L.append("```")
    L.append("")
    if payload_class:
        L.append(f"Recorded payloads ({payload_n}) with their technique and parameter. Read these "
                 "as *what was disclosed*; the engine still generates its own through "
                 "`fields.packet`/`record_payload` so authorship is recorded:")
        L.append("")
        L.append("```sh")
        L.append(f"sqlite3 {corpus_rel} \\")
        L.append(f"  \"SELECT technique, parameter, payload, report_url FROM payloads \\")
        L.append(f"   WHERE class_name='{payload_class}' LIMIT 40;\"")
        L.append("```")
        L.append("")
    L.append("## Reading these honestly")
    L.append("")
    L.append("- Titles and programs are upstream public-disclosure text, quoted as data.")
    L.append("- `reproduction_status` for the whole corpus is `not-reproduced`.")
    L.append("- Bounty absence means unknown-or-zero, not rejected.")
    L.append("- Class labels are the corpus's own; agreement with the vault index is 82%, "
             "and `vault/90-Meta/h1corpus-crosswalk.md` records the mapping.")
    return "\n".join(L) + "\n"


def main(argv: List[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--corpus", default=str(DEFAULT_CORPUS))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    corpus = Path(args.corpus)
    if not corpus.is_file():
        print(f"corpus not found: {corpus}", file=sys.stderr)
        return 2
    corpus_rel = str(corpus.relative_to(REPO)) if corpus.is_relative_to(REPO) else str(corpus)
    con = sqlite3.connect(f"file:{corpus}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row

    pay = {r["class_name"]: r["n"] for r in con.execute(
        "SELECT class_name, COUNT(*) n FROM payloads GROUP BY class_name")}

    written = skipped = 0
    for skill, classes in sorted(SKILL_CLASSES.items()):
        d = SKILLS / skill
        if not d.is_dir():
            print(f"  skip {skill}: no such skill directory")
            skipped += 1
            continue
        stat, top = fetch(con, classes)
        if not (stat.get("n") or 0):
            print(f"  skip {skill}: corpus has no reports for {classes}")
            skipped += 1
            continue
        pc = PAYLOAD_CLASSES.get(skill)
        body = render(skill, classes, stat, top, pc, pay.get(pc or "", 0), corpus_rel)
        out = d / "references" / "corpus.md"
        print(f"  {skill:26} {stat['n']:>5} reports  {stat.get('bodies') or 0:>5} bodies"
              f"  -> {out.relative_to(REPO)}")
        if not args.check:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(body, encoding="utf-8")
        written += 1
    print(f"\n  {'would write' if args.check else 'wrote'} {written} reference file(s), "
          f"skipped {skipped}")
    print("  SKILL.md files: untouched")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
